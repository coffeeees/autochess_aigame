function counts(list, key) {
  const out = {};
  for (const c of list) out[c[key]] = (out[c[key]] || 0) + 1;
  return out;
}

function toMarkdown() {
  const t = augment54;
  const c = counts(t.candidates, 'verdict');
  const lines = [
    `# 밸런스 테스트 — ${t.title}`,
    '',
    `- 날짜: ${t.date}`,
    `- 단계: ${t.stage}`,
    `- 테스트 방법: ${t.method}`,
    `- 실행 환경: ${t.environment}`,
    `- 완료 범위: ${t.scope}`,
    `- 판정 집계: ${t.verdicts.map((v) => `${v} ${c[v] || 0}`).join(' · ')}`,
    '',
    '## 실행하지 않은 테스트',
    ...t.notRun.map((x) => `- ${x}`),
    '',
    '## 현재 선택 규칙 대조',
    ...t.currentRules.map((x) => `- ${x}`),
    '',
    '## ID 충돌',
    t.idConflict,
    '',
    '## 54종 판정',
    '',
    '| ID | 이름 | 후보 효과 | 판정 | 구현 | 테스트 | 관련 현재 증강 | 메모 |',
    '|---|---|---|---|---|---|---|---|',
    ...t.candidates.map(
      (x) =>
        `| ${x.id} | ${x.name} | ${x.effect} | ${x.verdict} | ${x.status} | ${x.test} | ${x.related} | ${x.note} |`,
    ),
    '',
    '## 공통 예외 규칙 — 현재 코드의 동작',
    ...t.currentBehavior.map((x) => `- ${x}`),
    '',
    '## 결정이 필요한 사항',
    ...t.decisions.map((x, i) => `${i + 1}. ${x}`),
    '',
    '## 구현 묶음과 예상 작업량(합의 후)',
    ...t.plan.map(([what, size]) => `- [${size}] ${what}`),
    '',
  ];
  return lines.join('\n');
}

export default { augment54, counts, toMarkdown };
