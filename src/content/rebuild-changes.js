function toMarkdown() {
  const lines = [
    `# AUTOCHESS 재구축 변경 사항 (원본 ${base} 대비)`,
    '',
    '소스 구조 변경은 빼고, 플레이어가 겪는 동작·표시가 달라진 점만 정리했습니다.',
    '',
  ];
  for (const area of [...new Set(changes.map((c) => c.area))]) {
    lines.push(`## ${area}`, '');
    for (const c of changes.filter((x) => x.area === area))
      lines.push(`- [${c.kind}] **${c.title}**`, `  - 원본: ${c.before}`, `  - 지금: ${c.after}`);
    lines.push('');
  }
  return lines.join('\n');
}

