function recordMarkdown(t) {
  return [
    `# 밸런스 테스트 — ${t.title} (${t.version})`,
    '',
    `- 날짜: ${t.date}`,
    `- 테스트 방법: ${t.method}`,
    `- 실행 환경: ${t.environment}`,
    `- 범위: ${t.scope}`,
    '',
    '## 실행한 테스트',
    ...t.runs.map(
      (r) => `- [${r.kind}] ${r.name} — ${r.how}\n  - 결과: ${r.result} (${r.evidence})`,
    ),
    '',
    `## ${t.casesTitle || 'XP 사례별 예상값과 실제값'}`,
    '',
    '| 사례 | 예상 | 실제 | 판정 |',
    '|---|---|---|---|',
    ...t.cases.map((c) => `| ${c.join(' | ')} |`),
    '',
    `## ${t.growthTitle || '성장 속도'}`,
    ...t.growth.map((x) => `- ${x}`),
    '',
    '## 실행하지 않았거나 확인하지 못한 항목',
    ...t.notRun.map((x) => `- ${x}`),
    '',
    '## 발견한 문제',
    ...t.issues.map((x) => `- **${x.title}** [${x.status}] — ${x.detail}\n  - 재현: ${x.repro}`),
    '',
    '## 결정 사항(결정 결과와 새로 결정할 것)',
    ...t.decisions.map((x, i) => `${i + 1}. ${x}`),
    '',
    '## 수정한 파일',
    ...t.files.map((x) => `- ${x}`),
    '',
    '## 기존 시스템과의 관계',
    ...t.conflicts.map((x) => `- ${x}`),
    '',
  ].join('\n');
}

